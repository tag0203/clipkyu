import XCTest
@testable import ClipkyuCore

final class ClipboardStoreTests: XCTestCase {
    private struct Fixture {
        var store: ClipboardStore
        var clock: TimeInterval = 1_700_000_000

        @discardableResult
        mutating func copy(
            _ text: String,
            types: [String] = ["public.utf8-plain-text"]
        ) -> IngestResult {
            clock += 1
            return store.ingest(
                PasteboardSnapshot(text: text, types: types),
                now: Date(timeIntervalSince1970: clock)
            )
        }
    }

    func testDefaultMaxHistoryIs50() {
        XCTAssertEqual(ClipboardStore().maxHistory, 50)
        XCTAssertEqual(ClipboardStore.defaultMaxHistory, 50)
    }

    func testNormalCopyIsNewestFirstAndDoesNotQueue() {
        var fixture = Fixture(store: ClipboardStore())
        fixture.copy("A")
        fixture.copy("B")
        XCTAssertEqual(fixture.store.history.map(\.text), ["B", "A"])
        XCTAssertTrue(fixture.store.queue.isEmpty)
        XCTAssertNil(fixture.store.stagedID)
        XCTAssertEqual(fixture.store.mode, .normal)
    }

    func testConsecutiveDuplicatesCollapseAndNonConsecutiveStay() {
        var fixture = Fixture(store: ClipboardStore())
        fixture.copy("A")
        fixture.copy("A")
        fixture.copy("A")
        fixture.copy("B")
        fixture.copy("B")
        fixture.copy("A")
        XCTAssertEqual(fixture.store.history.map(\.text), ["A", "B", "A"])
    }

    func testWhitespaceOnlyTextIsKept() {
        var fixture = Fixture(store: ClipboardStore())
        let result = fixture.copy(" ")
        XCTAssertNil(result.skip)
        XCTAssertTrue(result.historyInserted)
        XCTAssertEqual(fixture.store.history.map(\.text), [" "])
    }

    func testEmptyAndMissingTextAreIgnored() {
        var store = ClipboardStore()
        let empty = store.ingest(PasteboardSnapshot(text: "", types: ["public.utf8-plain-text"]))
        let missing = store.ingest(PasteboardSnapshot(text: nil, types: ["public.utf8-plain-text"]))
        XCTAssertEqual(empty.skip, .empty)
        XCTAssertEqual(missing.skip, .notText)
        XCTAssertTrue(store.history.isEmpty)
        XCTAssertTrue(store.queue.isEmpty)
    }

    func testMaxHistoryDropsOldestAndDoesNotTrimTheQueue() {
        var fixture = Fixture(store: ClipboardStore(mode: .fifo, maxHistory: 2))
        fixture.copy("A")
        fixture.copy("B")
        fixture.copy("C")
        XCTAssertEqual(fixture.store.history.map(\.text), ["C", "B"])
        XCTAssertEqual(fixture.store.queue.map(\.text), ["A", "B", "C"])
        XCTAssertEqual(fixture.store.stagedItem()?.text, "A")
    }

    func testSetMaxHistoryTrimsNewestFirstAndRejectsZero() {
        var fixture = Fixture(store: ClipboardStore(maxHistory: 10))
        for text in ["A", "B", "C", "D"] {
            fixture.copy(text)
        }
        fixture.store.setMaxHistory(0)
        XCTAssertEqual(fixture.store.maxHistory, 1)
        XCTAssertEqual(fixture.store.history.map(\.text), ["D"])
        fixture.store.setMaxHistory(3)
        fixture.copy("E")
        fixture.copy("F")
        XCTAssertEqual(fixture.store.history.map(\.text), ["F", "E", "D"])
    }

    func testInitTrimsHistoryAndDropsDanglingStage() {
        let history = (0..<5).map {
            ClipItem(id: UUID(), text: "n\($0)", createdAt: Date(timeIntervalSince1970: Double($0)))
        }
        let store = ClipboardStore(maxHistory: 2, history: history, stagedID: UUID())
        XCTAssertEqual(store.history.map(\.text), ["n0", "n1"])
        XCTAssertNil(store.stagedID)
    }

    func testSensitiveMarkersAreSkippedInNormalAndQueueModes() {
        XCTAssertEqual(
            ClipboardStore.sensitiveTypeIdentifiers,
            [
                "org.nspasteboard.ConcealedType",
                "org.nspasteboard.TransientType",
                "org.nspasteboard.AutoGeneratedType",
            ]
        )
        for marker in ClipboardStore.sensitiveTypeIdentifiers {
            var fixture = Fixture(store: ClipboardStore(mode: .fifo))
            fixture.copy("safe")
            let skipped = fixture.copy(
                "secret",
                types: ["public.utf8-plain-text", marker]
            )
            XCTAssertEqual(skipped.skip, .sensitive, marker)
            XCTAssertFalse(skipped.enqueued, marker)
            XCTAssertFalse(skipped.historyInserted, marker)
            XCTAssertEqual(fixture.store.history.map(\.text), ["safe"], marker)
            XCTAssertEqual(fixture.store.queue.map(\.text), ["safe"], marker)
        }
    }

    func testPlainTextTypesAreNotSensitive() {
        XCTAssertFalse(ClipboardStore.isSensitive(types: ["public.utf8-plain-text"]))
        XCTAssertFalse(ClipboardStore.isSensitive(types: []))
    }

    func testInternalWriteIsIgnoredEvenWhenTheTextIsNew() {
        var fixture = Fixture(store: ClipboardStore(mode: .filo))
        fixture.copy("A")
        let before = fixture.store
        let result = fixture.store.ingest(
            PasteboardSnapshot(
                text: "brand new",
                types: [ClipboardStore.internalTypeIdentifier, "public.utf8-plain-text"]
            )
        )
        XCTAssertEqual(result.skip, .internalWrite)
        XCTAssertNil(result.stage)
        XCTAssertEqual(fixture.store, before)
    }

    func testFIFOStagesOldestAndAdvanceLeavesHistoryUntouched() {
        var fixture = Fixture(store: ClipboardStore(mode: .fifo))
        XCTAssertEqual(fixture.copy("A").stage?.text, "A")
        XCTAssertEqual(fixture.copy("B").stage?.text, "A")
        XCTAssertEqual(fixture.copy("C").stage?.text, "A")
        XCTAssertEqual(fixture.store.queue.map(\.text), ["A", "B", "C"])
        XCTAssertEqual(fixture.store.history.map(\.text), ["C", "B", "A"])
        let history = fixture.store.history

        XCTAssertEqual(fixture.store.advanceAfterPaste()?.text, "B")
        XCTAssertEqual(fixture.store.queue.map(\.text), ["B", "C"])
        XCTAssertEqual(fixture.store.advanceAfterPaste()?.text, "C")
        XCTAssertEqual(fixture.store.queue.map(\.text), ["C"])
        XCTAssertNil(fixture.store.advanceAfterPaste())
        XCTAssertTrue(fixture.store.queue.isEmpty)
        XCTAssertNil(fixture.store.stagedID)
        XCTAssertEqual(fixture.store.history, history)
    }

    func testFILOStagesNewestAndAdvanceLeavesHistoryUntouched() {
        var fixture = Fixture(store: ClipboardStore(mode: .filo))
        XCTAssertEqual(fixture.copy("A").stage?.text, "A")
        XCTAssertEqual(fixture.copy("B").stage?.text, "B")
        XCTAssertEqual(fixture.copy("C").stage?.text, "C")
        let history = fixture.store.history

        XCTAssertEqual(fixture.store.advanceAfterPaste()?.text, "B")
        XCTAssertEqual(fixture.store.queue.map(\.text), ["A", "B"])
        XCTAssertEqual(fixture.store.advanceAfterPaste()?.text, "A")
        XCTAssertEqual(fixture.store.queue.map(\.text), ["A"])
        XCTAssertNil(fixture.store.advanceAfterPaste())
        XCTAssertEqual(fixture.store.history, history)
        XCTAssertEqual(fixture.store.history.map(\.text), ["C", "B", "A"])
    }

    func testQueueKeepsDuplicateTextsWhileHistoryCollapses() throws {
        var fixture = Fixture(store: ClipboardStore(mode: .fifo))
        fixture.copy("A")
        let second = fixture.copy("A")
        XCTAssertFalse(second.historyInserted)
        XCTAssertTrue(second.enqueued)
        XCTAssertEqual(fixture.store.history.map(\.text), ["A"])
        XCTAssertEqual(fixture.store.queue.map(\.text), ["A", "A"])
        let historyID = fixture.store.history[0].id
        let stagedID = try XCTUnwrap(fixture.store.stagedID)
        XCTAssertEqual(stagedID, fixture.store.queue[0].id)

        XCTAssertEqual(fixture.store.advanceAfterPaste()?.text, "A")
        XCTAssertEqual(fixture.store.queue.map(\.text), ["A"])
        XCTAssertNotEqual(fixture.store.stagedID, stagedID)
        XCTAssertEqual(fixture.store.history.map(\.id), [historyID])
    }

    func testFILOAdvanceRemovesNewestDuplicateNotTheOldest() throws {
        var fixture = Fixture(store: ClipboardStore(mode: .filo))
        fixture.copy("A")
        fixture.copy("A")
        let oldestID = try XCTUnwrap(fixture.store.queue.first?.id)
        let newestID = try XCTUnwrap(fixture.store.queue.last?.id)
        XCTAssertNotEqual(oldestID, newestID)
        XCTAssertEqual(fixture.store.stagedID, newestID)
        _ = fixture.store.advanceAfterPaste()
        XCTAssertEqual(fixture.store.queue.map(\.id), [oldestID])
        XCTAssertEqual(fixture.store.history.count, 1)
    }

    func testSimulatedFIFOSessionIgnoresInternalRestage() {
        var fixture = Fixture(store: ClipboardStore(mode: .fifo))
        _ = fixture.copy("A")
        _ = fixture.copy("B")
        let stage = fixture.copy("C").stage
        let history = fixture.store.history
        XCTAssertEqual(stage?.text, "A")

        let ignored = fixture.store.ingest(
            PasteboardSnapshot(
                text: stage?.text,
                types: [ClipboardStore.internalTypeIdentifier, "public.utf8-plain-text"]
            )
        )
        XCTAssertEqual(ignored.skip, .internalWrite)

        while fixture.store.stagedItem() != nil {
            _ = fixture.store.advanceAfterPaste()
            if let next = fixture.store.stagedItem() {
                let restage = fixture.store.ingest(
                    PasteboardSnapshot(
                        text: next.text,
                        types: [ClipboardStore.internalTypeIdentifier]
                    )
                )
                XCTAssertEqual(restage.skip, .internalWrite)
            }
        }
        XCTAssertTrue(fixture.store.queue.isEmpty)
        XCTAssertEqual(fixture.store.history, history)
        XCTAssertEqual(fixture.store.history.map(\.text), ["C", "B", "A"])
    }

    func testClearQueueLeavesHistoryAndMode() {
        var fixture = Fixture(store: ClipboardStore(mode: .filo))
        fixture.copy("A")
        fixture.copy("B")
        let history = fixture.store.history
        fixture.store.clearQueue()
        XCTAssertTrue(fixture.store.queue.isEmpty)
        XCTAssertNil(fixture.store.stagedID)
        XCTAssertEqual(fixture.store.mode, .filo)
        XCTAssertEqual(fixture.store.history, history)
    }

    func testModeSwitchRestagesTheCorrectEndAndNormalKeepsTheQueue() {
        var fixture = Fixture(store: ClipboardStore(mode: .fifo))
        fixture.copy("A")
        fixture.copy("B")
        fixture.copy("C")
        let history = fixture.store.history
        let queue = fixture.store.queue

        XCTAssertEqual(fixture.store.setMode(.filo)?.text, "C")
        XCTAssertEqual(fixture.store.queue, queue)
        XCTAssertEqual(fixture.store.setMode(.normal)?.text, nil)
        XCTAssertNil(fixture.store.stagedItem())
        XCTAssertEqual(fixture.store.queue, queue)
        XCTAssertEqual(fixture.store.setMode(.fifo)?.text, "A")
        XCTAssertEqual(fixture.store.history, history)
        XCTAssertEqual(fixture.store.queue, queue)
    }

    func testAdvanceInNormalModeOrWithoutStageIsNoop() {
        var fixture = Fixture(store: ClipboardStore(mode: .normal))
        fixture.copy("A")
        let before = fixture.store
        XCTAssertNil(fixture.store.advanceAfterPaste())
        XCTAssertEqual(fixture.store, before)

        fixture.store.setMode(.fifo)
        fixture.store.clearQueue()
        XCTAssertNil(fixture.store.advanceAfterPaste())
        XCTAssertTrue(fixture.store.history.map(\.text) == ["A"])
    }

    func testSelectingHistoryDoesNotMutateStore() {
        var fixture = Fixture(store: ClipboardStore(mode: .fifo))
        fixture.copy("A")
        fixture.copy("B")
        let before = fixture.store
        let picked = fixture.store.historyItem(id: fixture.store.history[1].id)
        XCTAssertEqual(picked?.text, "A")
        XCTAssertEqual(fixture.store, before)
    }
}
